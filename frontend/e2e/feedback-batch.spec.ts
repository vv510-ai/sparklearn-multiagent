import { expect, test } from "@playwright/test";
import { registerLearner, currentAssessment } from "./intake-helpers";
test.use({ actionTimeout: 20_000 });

test("课程隔离、听力暂停恢复、改名持久化与移动阅读", async ({ page }, info) => {
  test.setTimeout(420_000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.addLocatorHandler(page.getByRole("button", { name: "跳过引导", exact: true }), b => b.click());
  await registerLearner(page, "batch-feedback");
  await page.getByRole("checkbox", { name: /从零开始，系统学习/ }).check();
  await page.getByRole("button", { name: "继续", exact: true }).click();
  await page.getByRole("radio", { name: "大学英语六级（CET-6）", exact: true }).check();
  for (let i = 0; i < 3; i++) await page.getByRole("button", { name: "继续", exact: true }).click();
  await page.getByRole("radio", { name: /完成所选范围摸底/ }).check();
  await page.getByRole("button", { name: "生成并核对学习范围", exact: true }).click();
  await page.getByRole("button", { name: "确认范围，开始独立作答", exact: true }).click();
  await expect(page.locator(".entry-question-card")).toBeVisible();
  let state = await currentAssessment(page);
  const notebookId = state.notebook_id;
  while (state.question && !state.question.audio_url) {
    const res = await page.request.post(`/api/assessment/${state.id}/answers`, { data: { revision: state.revision, question_id: state.question.id, status: "dont_know" } });
    expect(res.ok()).toBe(true); state = await res.json();
  }
  expect(state.question.audio_url).toBeTruthy();
  await page.reload();
  const card = page.locator(".entry-question-card");
  await card.locator('input[value="A"]').check();
  const submit = page.getByRole("button", { name: "提交，继续下一题" });
  await expect(submit).toBeDisabled();
  const audio = card.locator("audio");
  await expect.poll(() => audio.evaluate((e: HTMLAudioElement) => e.readyState)).toBeGreaterThanOrEqual(2);
  await audio.evaluate(async (e: HTMLAudioElement) => { e.muted = true; e.playbackRate = 4; await e.play(); });
  await expect(submit).toBeEnabled({ timeout: 40_000 });
  await page.getByRole("button", { name: "暂停，稍后继续", exact: true }).click();
  const oldSession = (await (await page.request.get(`/api/notebooks/${notebookId}?user_id=session_user`)).json()).session_id;
  await page.getByRole("button", { name: "新对话", exact: true }).click();
  await expect.poll(async () => (await (await page.request.get(`/api/notebooks/${notebookId}?user_id=session_user`)).json()).session_id).not.toBe(oldSession);
  await page.getByRole("button", { name: /^起点测评与计划/ }).click();
  await expect(card.locator('input[value="A"]')).toBeChecked();
  await expect(submit).toBeEnabled();
  await page.screenshot({ path: info.outputPath("resumed-listening.png") });
  await submit.click();
  await expect(card).not.toContainText(state.question.stem);
  await page.getByTitle("返回学习对话", { exact: true }).click();
  await expect(page.getByRole("button", { name: /^英语场景学习/ })).toBeVisible();
  await page.getByRole("button", { name: /^学习画像/ }).click();
  await expect(page.getByText("二叉树", { exact: true })).toHaveCount(0);
  await expect(page.getByText("高级排序", { exact: true })).toHaveCount(0);
  await page.getByTitle("返回学习对话", { exact: true }).click();
  await page.getByLabel("学习目标输入", { exact: true }).fill("请带我开始“词汇与语境”的第一项学习任务。先用一句话说清今天要学什么，再给我一个可以马上作答的小问题");
  await page.getByRole("button", { name: "发送", exact: true }).click();
  await expect(page.locator('[aria-label="小知回答"]').last()).toBeVisible();
  await expect(page.getByRole("button", { name: "停止生成", exact: true })).toHaveCount(0, { timeout: 180_000 });
  const generated = await page.request.post("/api/resources/generate", { timeout: 180_000, data: { user_id: "session_user", notebook_id: notebookId, kinds: ["doc"], prompt_template: "conversation_notes", goal: "整理本次学习对话", conversation_focus: "我今天要学习什么内容", source_ids: [] } });
  expect(generated.ok()).toBe(true); await generated.text();
  await page.getByRole("button", { name: /^资料归档/ }).click();
  const resources = (await (await page.request.get(`/api/resources?user_id=session_user&notebook_id=${notebookId}`)).json()).items;
  const note = resources.find((r: any) => r.payload.template === "conversation_notes");
  expect(note).toBeTruthy();
  const noteCard = page.locator('button[aria-expanded]').filter({ hasText: note.title }).first();
  if (await noteCard.getAttribute("aria-expanded") === "false") await noteCard.click();
  await page.getByRole("button", { name: "重命名", exact: true }).first().click();
  await page.getByLabel("资料名称", { exact: true }).fill("六级词汇复习笔记");
  await page.getByRole("button", { name: "保存名称", exact: true }).click();
  await expect(page.getByRole("button", { name: /六级词汇复习笔记/ })).toBeVisible();
  await page.getByRole("tablist").getByRole("button", { name: "讲解", exact: true }).click();
  await page.getByRole("tablist").getByRole("button", { name: "全部", exact: true }).click();
  await expect(page.getByRole("button", { name: /六级词汇复习笔记/ })).toBeVisible();
  const saved = await (await page.request.get(`/api/resources?user_id=session_user&notebook_id=${notebookId}`)).json();
  expect(saved.items.find((r: any) => r.id === note.id).title).toBe("六级词汇复习笔记");
  await page.reload();
  await page.getByRole("button", { name: /^资料归档/ }).click();
  await expect(page.getByRole("button", { name: /六级词汇复习笔记/ })).toBeVisible();
  await page.getByTitle("返回学习对话", { exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const input = page.getByLabel("学习目标输入", { exact: true });
  await input.fill("请一步步解释词汇的语境含义。\n请保留例句中的不确定性。\n第三行问题。\n第四行问题。");
  expect((await input.boundingBox())!.height).toBeGreaterThan(80);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "学习来源", exact: true }).click();
  const sourceDrawer = page.getByRole("dialog", { name: "学习来源", exact: true });
  await expect(sourceDrawer).toBeVisible();
  expect(await sourceDrawer.evaluate(el => {
    const style = getComputedStyle(el);
    return style.backgroundImage.includes("rgb(247, 250, 253)") || /^rgb\(/.test(style.backgroundColor);
  })).toBe(true);
  await page.screenshot({ path: info.outputPath("opaque-mobile-sheet.png") });
});

test("目录断网可继续选课，数学入口与期货推荐不串课", async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.addLocatorHandler(page.getByRole("button", { name: "跳过引导", exact: true }), b => b.click());
  await registerLearner(page, "batch-network");
  await page.getByRole("button", { name: "先进入，稍后继续", exact: true }).click();
  await page.route("**/api/notebooks/learning/catalogue", r => r.abort("failed"));
  await page.getByRole("button", { name: "新建课程", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "新建课程", exact: true });
  await expect(dialog).toContainText("仍可输入主题或上传课本");
  await dialog.getByRole("radio", { name: "上传课本生成课程", exact: true }).check();
  // Selection-only fixture; does not claim PDF parser acceptance.
  await dialog.getByLabel("上传课程课本", { exact: true }).setInputFiles({ name: "雅思练习.pdf", mimeType: "application/pdf", buffer: Buffer.from("%PDF-1.4") });
  await expect(dialog.getByRole("button", { name: "创建并进入", exact: true })).toBeEnabled();
  await expect(dialog.getByRole("alert")).toHaveCount(0);
  await dialog.getByRole("button", { name: "取消", exact: true }).click();
  await page.unroute("**/api/notebooks/learning/catalogue");
  const book = await (await page.request.post("/api/notebooks", { data: { title: "高等数学", user_id: "session_user" } })).json();
  await page.reload();
  await page.getByRole("combobox", { name: "切换科目书本" }).selectOption(book.id);
  await expect(page.getByRole("button", { name: /^英语场景学习/ })).toHaveCount(0);
  const futures = await (await page.request.post("/api/notebooks", { data: { title: "期货入门", user_id: "session_user" } })).json();
  await page.reload();
  await page.getByRole("combobox", { name: "切换科目书本" }).selectOption(futures.id);
  await page.route("**/api/courses?*", r => r.abort("failed"));
  await page.getByRole("button", { name: /^推荐网课/ }).click();
  await expect(page.getByRole("link", { name: /YouTube 搜索/ })).toHaveAttribute("href", /search_query=%E6%9C%9F%E8%B4%A7/);
  await page.screenshot({ path: info.outputPath("course-network-recovery.png") });
});


test("导图实际加载并响应逐个查看、缩放复位与高度切换", async ({ page }, info) => {
  test.setTimeout(180_000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.addLocatorHandler(page.getByRole("button", { name: "跳过引导", exact: true }), b => b.click());
  await registerLearner(page, "batch-map");
  await page.getByRole("button", { name: "先进入，稍后继续", exact: true }).click();
  const book = await (await page.request.post("/api/notebooks", { data: { user_id: "session_user", title: "数据结构复习" } })).json();
  const prepared = await page.request.post(`/api/notebooks/${book.id}/learning/prepare`, { data: { title: "数据结构复习", course_key: "ds_algo", source_ids: [] } });
  expect(prepared.ok()).toBe(true);
  const generated = await page.request.post("/api/resources/generate", { timeout: 120_000, data: { user_id: "session_user", notebook_id: book.id, kinds: ["mindmap"], goal: "整合二叉树与队列的学习框架", conversation_focus: "什么是二叉树和队列", prompt_template: "framework", artifact_scope: "conversation", source_ids: [] } });
  expect(generated.ok()).toBe(true); await generated.text();
  await page.reload();
  await page.getByRole("combobox", { name: "切换科目书本" }).selectOption(book.id);
  await page.getByRole("button", { name: /^资料归档/ }).click();
  await page.locator('button[aria-expanded]').filter({ hasText: "本次对话·知识全景导图" }).click();
  const map = page.locator(".markmap-light");
  await expect(map.getByRole("button", { name: "逐个查看", exact: true })).toBeEnabled();
  await map.getByRole("button", { name: "逐个查看", exact: true }).click();
  await expect(map.getByRole("status")).toContainText("1 /");
  await expect(map.locator(".markmap-node-active")).toHaveCount(1);
  await map.getByRole("button", { name: "停止逐个查看", exact: true }).click();
  const svg = map.locator("svg.markmap-canvas");
  const before = (await svg.boundingBox())!.height;
  await map.getByRole("button", { name: /恢复高度|放大查看/ }).click();
  await expect.poll(async () => Math.abs((await svg.boundingBox())!.height - before)).toBeGreaterThan(100);
  await svg.hover(); await page.mouse.wheel(0, -200);
  const zoomed = await svg.locator("g").first().getAttribute("transform");
  await map.getByRole("button", { name: "适配视图", exact: true }).click();
  await expect.poll(() => svg.locator("g").first().getAttribute("transform")).not.toBe(zoomed);
  await page.screenshot({ path: info.outputPath("map-controls.png") });
});
